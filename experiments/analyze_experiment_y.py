def _fit_m(res, reader, rep, field):
    return res["readers"][reader][rep]["fit"][field]["mean"]


def _state_m(res, reader, rep, state, field, pop):
    return res["readers"][reader][rep][state][field][pop]["mean"]


def classify(res: Dict[str, Any]) -> Dict[str, Any]:
    per_pair: Dict[str, Any] = {}
    for R in SEQUENCE_READERS:
        for rep in DECISIVE:
            tr_max = _fit_m(res, R, rep, "train_acc_max")
            tr_final = _fit_m(res, R, rep, "train_acc_final")
            ho = {st: _state_m(res, R, rep, st, "heldout", f"{PRIMARY_MODEL}:classA")
                  for st in _STATES}
            tst = {st: _state_m(res, R, rep, st, "acc", f"{PRIMARY_MODEL}:classA") for st in _STATES}
            vals = [v for v in ho.values() if v is not None]
            per_pair[f"{R}|{rep}"] = {
                "train_acc_max": tr_max, "train_acc_final": tr_final,
                "heldout_classA": ho, "test_classA": tst,
                "max_heldout_classA": max(vals) if vals else None,
                "fits": bool(tr_max is not None and tr_max >= FIT_BAR),
                "weak_heldout": bool(vals and max(vals) <= HELDOUT_WEAK),
            }
    fam_fits = {R: any(per_pair[f"{R}|{rep}"]["fits"] for rep in DECISIVE)
                for R in SEQUENCE_READERS}
    fitting_pairs = [k for k, v in per_pair.items() if v["fits"]]
    all_fitting_weak = all(per_pair[k]["weak_heldout"] for k in fitting_pairs) if fitting_pairs else None
    if fam_fits["GRU"] != fam_fits["TCN"]:
        verdict = "Y-MIX"
    elif any(fam_fits.values()):
        verdict = "Y-A" if all_fitting_weak else "Y-inconclusive"
    else:
        verdict = "Y-B"
    # control reader (MLP-128), reported but not in the headline
    control = {}
    for rep in DECISIVE:
        control[rep] = {"train_acc_max": _fit_m(res, "MLP128", rep, "train_acc_max"),
                        "train_acc_final": _fit_m(res, "MLP128", rep, "train_acc_final"),
                        "heldout_classA": _state_m(res, "MLP128", rep, "best_val", "heldout",
                                                   f"{PRIMARY_MODEL}:classA"),
                        "test_classA": _state_m(res, "MLP128", rep, "best_val", "acc",
                                                f"{PRIMARY_MODEL}:classA")}
    best_tr = max((v["train_acc_max"] for v in per_pair.values() if v["train_acc_max"] is not None),
                  default=None)
    best_ho = min((v["max_heldout_classA"] for v in per_pair.values()
                   if v["max_heldout_classA"] is not None), default=None)
    return {"verdict": verdict, "per_pair": per_pair, "family_fits": fam_fits,
            "fitting_pairs": fitting_pairs, "all_fitting_weak": all_fitting_weak,
            "best_sequence_train_max": best_tr, "min_sequence_max_heldout": best_ho,
            "mlp128_control": control,
            "thresholds": {"fit_bar": FIT_BAR, "test_weak": TEST_WEAK,
                           "heldout_weak": HELDOUT_WEAK, "heldout_material": HELDOUT_MATERIAL},
            "rule_note": ("Y-MIX if the GRU and TCN reach materially different fitting outcomes "
                          "(one family >=0.90 train, the other not); else Y-A if some GRU/TCN at "
                          "L4/full reaches >=0.90 training accuracy on the 256-subset AND its "
                          "held-out Class-A target accuracy (max over the reported states) stays "
                          "<=0.25; else Y-B if neither sequence reader reaches 0.90 training "
                          "accuracy at either history condition; else Y-inconclusive. Bars are "
                          "declared conventions; continuous values reported.")}


def _collect(data: Dict[str, Any], jobs: int, readers: List[str]) -> List[Dict[str, Any]]:
    npz_path = data["path"]
    arch = av.architecture()
    specs = [(s, R) for s in SEEDS for R in readers]
    t0 = time.perf_counter()
    if jobs <= 1:
        _init_worker(npz_path, arch)
        return [_task(sp) for sp in specs]
    ctx = mp.get_context("fork")
    with ctx.Pool(processes=jobs, initializer=_init_worker, initargs=(npz_path, arch)) as pool:
        out = list(pool.imap_unordered(_task, specs, chunksize=1))
    print(f"collection wall_seconds={time.perf_counter() - t0:.1f}", flush=True)
    return sorted(out, key=lambda r: (r["seed"], r["reader"]))


def assemble(data: Dict[str, Any], per: List[Dict[str, Any]], w_meta: Dict[str, Any],
             baselines: Dict[str, Any]) -> Dict[str, Any]:
    arch = av.architecture()
    readers, traj = aggregate(per)
    res: Dict[str, Any] = {"metadata": {
        "date": time.strftime("%Y-%m-%d %H:%M:%S"), "seeds": SEEDS, "readers": READERS,
        "sequence_readers": SEQUENCE_READERS, "reps": DECISIVE, "target": "y_true",
        "updates": UPDATES, "eval_every": EVAL_EVERY, "milestones": MILESTONES,
        "subset_size": data["meta"]["subset_size"], "subset_seed": data["meta"]["subset_seed"],
        "subset_per_seed": data["meta"]["n"]["subset_per_seed"],
        "populations": POPULATIONS, "heldout_pairs": sorted(HELD_OUT_PAIRS),
        "reader_lr": av.READER_LR, "reader_wd": av.READER_WD, "mlp_lr": as_.MLP_LR,
        "mlp_wd": as_.MLP_WD,
        "data_identity": {"source_npz": data["meta"]["source"]["npz"],
                          "source_sha256": data["meta"]["source"]["sha256"],
                          "per_seed": data["meta"]["per_seed"],
                          "disjointness": data["meta"]["disjointness"]},
        "checkpoints": data["meta"]["models"], "n": data["meta"]["n"],
        "thresholds": {"fit_bar": FIT_BAR, "test_weak": TEST_WEAK,
                       "heldout_weak": HELDOUT_WEAK, "heldout_material": HELDOUT_MATERIAL},
        "statistical_discipline": (
            "Five frozen E checkpoints are the independent units; F is a control. The three readers "
            "are analysis-only, fit on the fixed 256-transition class-balanced subset with W/X's "
            "exact optimizer protocol, tuned on the fixed canonical VAL, evaluated once on the "
            "untouched canonical TEST. The ONLY factor is the fitting-set size (256 vs W's 10,000). "
            "Checkpoint selection is VAL-only; the best-on-TRAIN state is a diagnostic and is never "
            "used to select a deployable model; TEST is never used to select or adjust.")}}
    res["architecture"] = arch
    res["readers"] = readers
    res["trajectory"] = traj
    res["per_seed"] = per
    res["baselines"] = baselines
    res["w_meta_train_sizes"] = w_meta.get("train_sizes")
    res["primary_decision"] = classify(res)
    return res


def build(data: Dict[str, Any], w_meta: Dict[str, Any], baselines: Dict[str, Any], jobs: int,
          readers: Optional[List[str]] = None) -> Dict[str, Any]:
    return assemble(data, _collect(data, jobs, readers or READERS), w_meta, baselines)


