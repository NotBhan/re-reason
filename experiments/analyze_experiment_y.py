def make_figures(d, res, out_dir, prefix="experiment_y") -> List[str]:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    os.makedirs(out_dir, exist_ok=True)
    paths: List[str] = []

    def save(fig, name):
        p = os.path.join(out_dir, f"{prefix}_{name}.png")
        fig.savefig(p, dpi=150, bbox_inches="tight")
        plt.close(fig)
        paths.append(p)

    def nz(v):
        return np.nan if v is None else v

    R = res["readers"]
    colors = {"MLP128": "tab:green", "GRU": "tab:blue", "TCN": "tab:orange"}

    def fit_m(reader, rep, field):
        return nz(R[reader][rep]["fit"][field]["mean"])

    def st_m(reader, rep, state, field, pop=f"{PRIMARY_MODEL}:classA"):
        return nz(R[reader][rep][state][field][pop]["mean"])

    groups = [f"{r}\n{rep}" for r in READERS for rep in DECISIVE]
    gx = np.arange(len(groups))

    # 1 training fit: max vs final training accuracy
    fig, ax = plt.subplots(figsize=(9.0, 4.6))
    best = [fit_m(r, rep, "train_acc_max") for r in READERS for rep in DECISIVE]
    final = [fit_m(r, rep, "train_acc_final") for r in READERS for rep in DECISIVE]
    ax.bar(gx - 0.2, best, 0.4, label="max training accuracy", color="tab:blue")
    ax.bar(gx + 0.2, final, 0.4, label="final training accuracy", color="tab:cyan")
    ax.axhline(FIT_BAR, ls="--", c="k", lw=0.9, label="0.90 fit bar")
    ax.set_xticks(gx); ax.set_xticklabels(groups, fontsize=8)
    ax.set_ylim(0, 1.02); ax.set_xlabel("reader / history")
    ax.set_ylabel("accuracy on the 256-example subset")
    ax.legend(fontsize=8); ax.grid(alpha=0.3, axis="y")
    ax.set_title("Y: can the bounded readers fit the 256-example subset?")
    save(fig, "training_fit")

    # 2 training trajectory: train vs val accuracy vs update
    T = res.get("trajectory", {})
    fig, ax = plt.subplots(figsize=(9.0, 4.8))
    for reader in READERS:
        for rep, ls in (("L4", "-"), ("Lfull", "--")):
            node = T.get(reader, {}).get(rep)
            if not node:
                continue
            ax.plot(node["updates"], [v["mean"] for v in node["train_acc"]], ls=ls,
                    color=colors[reader], alpha=1.0 if rep == "L4" else 0.6,
                    label=f"{reader} {rep} train")
            ax.plot(node["updates"], [v["mean"] for v in node["val_acc"]], ls=":", color=colors[reader],
                    alpha=1.0 if rep == "L4" else 0.6, label=f"{reader} {rep} val")
    ax.axhline(FIT_BAR, ls="--", c="k", lw=0.8, label="0.90 fit bar")
    ax.set_xlabel("optimizer updates"); ax.set_ylabel("accuracy")
    ax.set_ylim(0, 1.02); ax.legend(fontsize=6, ncol=3); ax.grid(alpha=0.3)
    ax.set_title("Y: training / validation accuracy trajectory (256-example subset)")
    save(fig, "training_trajectory")

    # 3 train vs test
    fig, ax = plt.subplots(figsize=(8.6, 4.6))
    for r in READERS:
        for rep in DECISIVE:
            xv = fit_m(r, rep, "train_acc_max")
            yv = st_m(r, rep, "best_val", "acc")
            ax.scatter(xv, yv, color=colors[r], s=70, zorder=3)
            ax.annotate(f"{r} {rep}", (xv, yv), fontsize=7, xytext=(4, 4), textcoords="offset points")
    ax.axvline(FIT_BAR, ls="--", c="k", lw=0.8, label="0.90 fit bar")
    ax.axhline(TEST_WEAK, ls=":", c="gray", lw=0.8, label="0.25 weak")
    ax.set_xlim(0, 1.02); ax.set_ylim(0, 1.02)
    ax.set_xlabel("max training accuracy (256-example subset)")
    ax.set_ylabel("Class-A TEST accuracy (best-on-VAL)")
    ax.legend(fontsize=8); ax.grid(alpha=0.3)
    ax.set_title("Y: fitting vs task generalization")
    save(fig, "train_vs_test")

    # 4 held-out generalization (Class-A): seen vs held-out at best-on-VAL
    fig, ax = plt.subplots(figsize=(9.0, 4.6))
    seen = [st_m(r, rep, "best_val", "seen") for r in READERS for rep in DECISIVE]
    hold = [st_m(r, rep, "best_val", "heldout") for r in READERS for rep in DECISIVE]
    ax.bar(gx - 0.2, seen, 0.4, label="seen operand pairs", color="tab:gray")
    ax.bar(gx + 0.2, hold, 0.4, label="held-out operand pairs", color="tab:purple")
    ax.axhline(HELDOUT_MATERIAL, ls=":", c="k", lw=0.8, label="0.30 material")
    ax.axhline(HELDOUT_WEAK, ls=":", c="gray", lw=0.8, label="0.25 weak")
    ax.set_xticks(gx); ax.set_xticklabels(groups, fontsize=8); ax.set_ylim(0, 1.02)
    ax.set_ylabel("Class-A accuracy (best-on-VAL)")
    ax.legend(fontsize=8); ax.grid(alpha=0.3, axis="y")
    ax.set_title("Y: seen vs held-out operand generalization (Class-A)")
    save(fig, "heldout_generalization")

    # 5 reader comparison (fit / test / held-out)
    fig, ax = plt.subplots(figsize=(8.6, 4.6))
    x3 = np.arange(len(READERS))
    ax.bar(x3 - 0.25, [max(fit_m(r, rep, "train_acc_max") for rep in DECISIVE) for r in READERS],
           0.25, label="max train", color="tab:blue")
    ax.bar(x3, [max(st_m(r, rep, "best_val", "acc") for rep in DECISIVE) for r in READERS],
           0.25, label="best test (Class-A)", color="tab:red")
    ax.bar(x3 + 0.25, [max(st_m(r, rep, "best_val", "heldout") for rep in DECISIVE) for r in READERS],
           0.25, label="best held-out", color="tab:purple")
    ax.axhline(FIT_BAR, ls="--", c="k", lw=0.8)
    ax.set_xticks(x3); ax.set_xticklabels(READERS)
    ax.set_ylim(0, 1.02); ax.set_ylabel("accuracy"); ax.legend(fontsize=8); ax.grid(alpha=0.3, axis="y")
    ax.set_title("Y: reader comparison (best over L4/full)")
    save(fig, "reader_comparison")

    # 6 L4 vs full
    fig, ax = plt.subplots(figsize=(8.6, 4.6))
    xi = np.arange(len(READERS))
    ax.bar(xi - 0.3, [fit_m(r, "L4", "train_acc_max") for r in READERS], 0.2, label="L4 train(max)",
           color="tab:blue")
    ax.bar(xi - 0.1, [st_m(r, "L4", "best_val", "heldout") for r in READERS], 0.2, label="L4 held-out",
           color="tab:purple")
    ax.bar(xi + 0.1, [fit_m(r, "Lfull", "train_acc_max") for r in READERS], 0.2, label="full train(max)",
           color="tab:cyan")
    ax.bar(xi + 0.3, [st_m(r, "Lfull", "best_val", "heldout") for r in READERS], 0.2,
           label="full held-out", color="tab:pink")
    ax.axhline(FIT_BAR, ls="--", c="k", lw=0.8)
    ax.set_xticks(xi); ax.set_xticklabels(READERS); ax.set_ylim(0, 1.02)
    ax.set_ylabel("accuracy"); ax.legend(fontsize=7); ax.grid(alpha=0.3, axis="y")
    ax.set_title("Y: L4 vs full-prefix")
    save(fig, "l4_vs_full")

    # 7 per-seed
    fig, ax = plt.subplots(figsize=(8.6, 4.6))
    xs = np.arange(len(SEEDS))
    for reader in READERS:
        for rep, ls in (("L4", "-"), ("Lfull", "--")):
            vals = [s["fits"][f"{reader}|{rep}"]["fit"]["train_acc_max"]
                    for s in res["per_seed"] if s["reader"] == reader]
            ax.plot(xs, vals, marker="o", ls=ls, color=colors[reader],
                    alpha=1.0 if rep == "L4" else 0.6, label=f"{reader} {rep}")
    ax.axhline(FIT_BAR, ls="--", c="k", lw=0.8, label="0.90 fit bar")
    ax.set_xticks(xs); ax.set_xticklabels([str(s) for s in SEEDS]); ax.set_xlabel("E seed")
    ax.set_ylabel("max training accuracy (256-example subset)"); ax.set_ylim(0, 1.02)
    ax.legend(fontsize=7, ncol=2); ax.grid(alpha=0.3)
    ax.set_title("Y: per-seed small-subset fitting")
    save(fig, "per_seed")

    # 8 decision summary
    fig, ax = plt.subplots(figsize=(8.6, 4.6))
    d = res["primary_decision"]
    cats = ["best sequence\ntrain (max)", "min sequence\nmax held-out", "best sequence\ntest (Class-A)"]
    seq_tr = [nz(d["per_pair"][k]["train_acc_max"]) for k in d["per_pair"]]
    seq_ho = [nz(d["per_pair"][k]["max_heldout_classA"]) for k in d["per_pair"]]
    seq_te = [nz(d["per_pair"][k]["test_classA"]["best_val"]) for k in d["per_pair"]]
    vals = [max(seq_tr) if seq_tr else np.nan, min(seq_ho) if seq_ho else np.nan,
            max(seq_te) if seq_te else np.nan]
    ax.bar(np.arange(3), vals, color=["tab:blue", "tab:purple", "tab:red"])
    ax.axhline(FIT_BAR, ls="--", c="k", lw=0.8, label="0.90 fit bar")
    ax.axhline(HELDOUT_WEAK, ls=":", c="gray", lw=0.8, label="0.25 weak")
    ax.set_xticks(np.arange(3)); ax.set_xticklabels(cats, fontsize=8)
    ax.set_ylim(0, 1.02); ax.set_ylabel("value"); ax.legend(fontsize=8); ax.grid(alpha=0.3, axis="y")
    ax.set_title(f"Y: decision summary ({d['verdict']})")
    save(fig, "decision_summary")
    return paths


def main() -> None:
    global TOP
    ap = argparse.ArgumentParser(description="Experiment Y analysis (measurement only)")
    ap.add_argument("--npz", default="experiments/experiment_y_fitting_control.npz")
    ap.add_argument("--w-results", default="experiments/experiment_w_results.json")
    ap.add_argument("--x-results", default="experiments/experiment_x_results.json")
    ap.add_argument("--output", default="experiments/experiment_y_results.json")
    ap.add_argument("--fig-dir", default="docs/reports/figures")
    ap.add_argument("--fig-prefix", default="experiment_y")
    ap.add_argument("--jobs", type=int, default=5)
    ap.add_argument("--readers", nargs="*", default=None,
                    help="subset of readers to fit (MLP128 GRU TCN); default all")
    args = ap.parse_args()
    data = load(args.npz)
    data["path"] = args.npz
    TOP = int(data["meta"]["source"]["top_size"])
    aw.TRAIN_SIZES = list(data["meta"]["source"]["train_sizes"])
    baselines = load_baselines(args.w_results, args.x_results, TOP)
    t0 = time.perf_counter()
    res = build(data, data["meta"], baselines, args.jobs, readers=args.readers)
    print(f"analysis wall_seconds={time.perf_counter() - t0:.1f}", flush=True)
    os.makedirs(os.path.dirname(args.output), exist_ok=True)
    with open(args.output, "w") as f:
        json.dump(res, f, indent=2)
    print(f"Wrote {args.output}")
    d = res["primary_decision"]
    print(f"verdict: {d['verdict']}  family_fits={d['family_fits']}")
    for k, v in d["per_pair"].items():
        print(f"  {k}: train_max={v['train_acc_max']:.3f} final={v['train_acc_final']:.3f} "
              f"heldout(max)={v['max_heldout_classA']} test(best_val)={v['test_classA']['best_val']}")
    print("  MLP128 control:", {k: {kk: vv for kk, vv in v.items()} for k, v in d["mlp128_control"].items()})
    paths = make_figures(data, res, args.fig_dir, prefix=args.fig_prefix)
    print(f"Figures: {len(paths)}")


if __name__ == "__main__":
    main()
