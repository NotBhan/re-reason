#!/usr/bin/env python3
"""Experiment Y — analysis: bounded-reader fitting control at fixed capacity and data.

X (X-B) established that the three bounded, analysis-only readers (U's flat MLP-128, V's causal GRU,
V's causal TCN) do not fit even the fixed 10,000-transition training pool (training accuracy
0.07-0.15, near/below the 0.10 chance) under the fixed protocol. Y asks the single diagnostic
question that can separate "the ADD task is the obstacle" from "the reader training pipeline is the
obstacle":

    Can the existing bounded readers FIT the actual register-tracking target (y_true) on a small,
    fixed, class-balanced training subset (256 unique ordinary-ADD transitions/seed) under the
    same fixed optimizer protocol?

Y manipulates exactly ONE factor for the fitting diagnostic: the fitting set size (256 vs W's
10,000). The reader architectures/widths, optimizer (Adam 3e-3, weight-decay 1e-2), class-balanced
CE loss, full-batch regime, history representations (22-dim = 21 raw + validity bit), targets
(y_true), VAL/TEST splits, held-out operand protocol and deterministic fit seeds are all REUSED
verbatim from U/V/W/X. The readers remain separate analysis-only models.

PRE-REGISTRATION (declared before aggregate inspection)
-------------------------------------------------------
* Two history conditions only: `L4` and `Lfull`; primary target `y_true` = `(operand_a + operand_b)
  mod 10` generated by the existing helpers. No new target types, no architecture variants.
* Fitting set (fixed): 256 unique ordinary-ADD transitions/seed, stratified by `y_true` over its 10
  classes (6x26 + 4x25 for size 256), held-out operand pairs `(a,b) with b in {0,5}` excluded, no
  duplication; the same subset is used for all three readers and both history conditions; selected
  deterministically before any fitting (seed `20261010`), never from reader performance.
* Training: X's exact protocol — Adam 3e-3, weight-decay 1e-2, full-batch, class-balanced CE,
  exactly 1,000 optimizer updates, deterministic per-fit seed, VAL evaluated every 10 updates.
* Checkpoint reporting: the FINAL state (after exactly 1,000 updates), the best-on-VAL state
  (validation-only selection), and the best-on-TRAIN state (a diagnostic, never a deployable
  selection). TEST is never used to select a checkpoint or adjust the experiment.
* Decision (checked in order; bars are declared conventions):
    Y-MIX             : the GRU and TCN reach materially different fitting outcomes (one family
                        reaches >= 0.90 training accuracy and the other does not).
    Y-A               : some sequence reader (GRU/TCN) at L4/full reaches training accuracy
                        >= 0.90 on the 256-subset AND its held-out Class-A target accuracy stays
                        <= 0.25.
    Y-B               : neither sequence reader reaches 0.90 training accuracy at either history
                        condition after 1,000 updates.
    Y-inconclusive    : any case between the above (reported explicitly, not re-categorised).
* MLP-128 is reported as a control; the headline decision focuses on the two sequence readers.
* W's 200-update and X's 1,000-update full-pool results are reused UNCHANGED for comparison; no new
  full-pool sweep is run. `op_dest` is cited as the prior directly-observable control, not re-run.

Reproduce:
    PYTHONPATH=src python experiments/analyze_experiment_y.py \
        --npz experiments/experiment_y_fitting_control.npz \
        --w-results experiments/experiment_w_results.json \
        --x-results experiments/experiment_x_results.json \
        --output experiments/experiment_y_results.json \
        --fig-dir docs/reports/figures --fig-prefix experiment_y
"""

