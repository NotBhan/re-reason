def train_trajectory(reader: str, Xtr, ytr, Xva, yva, nclass: int, seed: int, updates: int,
                     arch: Dict[str, Any], eval_every: int = EVAL_EVERY) -> Dict[str, Any]:
    """Run `updates` full-batch Adam updates, evaluating VAL every `eval_every`.

    Ops/order are identical to U/V/W's readers and to X's `train_trajectory` (same seed, data,
    optimizer, loss), so the best-on-VAL state reproduces X's bit-for-bit; additionally the FINAL
    state after exactly `updates` updates and the best-on-TRAIN state (diagnostic) are returned.
    """
    import torch
    import torch.nn.functional as F
    torch.manual_seed(seed)
    if reader == "MLP128":
        Xtr = np.asarray(Xtr, dtype=np.float64)
        Xva = np.asarray(Xva, dtype=np.float64)
        m = Xtr.mean(0)
        s = Xtr.std(0) + 1e-6
        Xn = torch.tensor((Xtr - m) / s, dtype=torch.float32)
        Xv = torch.tensor((Xva - m) / s, dtype=torch.float32)
        indim = int(Xtr.shape[1])
        lr, wd = as_.MLP_LR, as_.MLP_WD
        norm: Optional[Tuple[np.ndarray, np.ndarray]] = (m, s)
    else:
        Xn = torch.tensor(Xtr, dtype=torch.float32)
        Xv = torch.tensor(Xva, dtype=torch.float32)
        indim = av.INPUT_DIM
        lr, wd = av.READER_LR, av.READER_WD
        norm = None
    model = ax.build_model(reader, nclass, indim, arch)
    yn = torch.tensor(ytr, dtype=torch.long)
    yv = torch.tensor(yva, dtype=torch.long)
    wc = torch.tensor(as_.class_weights(ytr, nclass), dtype=torch.float32)
    opt = torch.optim.Adam(model.parameters(), lr=lr, weight_decay=wd)
    best_val: Tuple[float, Any, int] = (-1.0, None, -1)
    best_train: Tuple[float, Any, int] = (-1.0, None, -1)
    events: List[Dict[str, float]] = []
    for ep in range(updates):
        model.train()
        opt.zero_grad()
        loss = F.cross_entropy(model(Xn), yn, weight=wc)
        loss.backward()
        opt.step()
        if (ep + 1) % eval_every == 0:
            model.eval()
            with torch.no_grad():
                vlog = model(Xv)
                vloss = float(F.cross_entropy(vlog, yv, weight=wc))
                vacc = float((vlog.argmax(1) == yv).float().mean())
                trlog = model(Xn)
                trloss = float(F.cross_entropy(trlog, yn, weight=wc))
                tracc = float((trlog.argmax(1) == yn).float().mean())
            events.append({"update": ep + 1, "train_loss": trloss, "train_acc": tracc,
                           "val_loss": vloss, "val_acc": vacc})
            st = {k: v.clone() for k, v in model.state_dict().items()}
            if vacc > best_val[0]:
                best_val = (vacc, st, ep + 1)
            if tracc > best_train[0]:
                best_train = (tracc, st, ep + 1)
    final = {k: v.clone() for k, v in model.state_dict().items()}
    if best_val[1] is None:
        best_val = (events[-1]["val_acc"], {k: v.clone() for k, v in final.items()}, updates)
    if best_train[1] is None:
        best_train = (events[-1]["train_acc"], {k: v.clone() for k, v in final.items()}, updates)
    return {"events": events, "best_val": best_val, "best_train": best_train, "final": final,
            "norm": norm, "train_acc_final": events[-1]["train_acc"],
            "train_loss_final": events[-1]["train_loss"], "val_acc_final": events[-1]["val_acc"],
            "val_loss_final": events[-1]["val_loss"]}


def predict_state(reader: str, state, X, norm, nclass: int, indim: int, arch) -> np.ndarray:
    return ax.predict_state(reader, state, X, norm, nclass, indim, arch)


